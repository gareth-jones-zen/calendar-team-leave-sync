"""Writes src/TeamLeave/CaseFold.g.cs: Python's case-insensitive matching data (re.IGNORECASE on str patterns), so
the .NET version matches hand-made entries' titles exactly as Python's re does, whatever the name's script.

    python tests/parity/gen_casefold.py

Python's rule (re/_compiler.py and _sre, checked against re itself for every cased code point): a pattern character
c that is cased matches a character d when lower(d) is lower(c), or one of _EXTRA_CASES[lower(c)]; a character that
isn't cased matches only itself. lower() is _sre.unicode_tolower, the simple lower-case mapping of Python's Unicode
database. .NET's RegexOptions.IgnoreCase differs (it doesn't match a final sigma to a capital sigma, for one).
"""

import _sre
import pathlib
import sys
from re._casefix import _EXTRA_CASES

ROOT = pathlib.Path(__file__).resolve().parents[2]
lower = [(c, _sre.unicode_tolower(c)) for c in range(0x110000)
         if not 0xD800 <= c <= 0xDFFF and _sre.unicode_tolower(c) != c]
self_lower_cased = [c for c in range(0x110000)
                    if not 0xD800 <= c <= 0xDFFF and _sre.unicode_iscased(c) and _sre.unicode_tolower(c) == c]
extra = sorted(_EXTRA_CASES.items())


def ints(values):
    out, line = [], "        "
    for v in values:
        item = f"0x{v:X}, "
        if len(line) + len(item) > 118:
            out.append(line.rstrip())
            line = "        "
        line += item
    out.append(line.rstrip())
    return "\n".join(out)


text = f"""// <auto-generated>
// Made by tests/parity/gen_casefold.py from Python {sys.version.split()[0]} (Unicode {__import__('unicodedata').unidata_version}). Don't edit by hand.
// </auto-generated>
namespace TeamLeave;

internal static partial class CaseFold
{{
    /// <summary>(code point, its lower case) for every code point whose simple lower case differs.</summary>
    private static readonly int[] LowerPairs =
    [
{ints(v for pair in lower for v in pair)}
    ];

    /// <summary>Cased code points that are their own lower case (they have an upper case).</summary>
    private static readonly int[] CasedLower =
    [
{ints(self_lower_cased)}
    ];

    /// <summary>re._casefix._EXTRA_CASES: lower case, then the extra characters it also matches, then -1.</summary>
    private static readonly int[] Extra =
    [
{ints(v for k, vs in extra for v in (k, *vs, -1) if v != -1)}
    ];

    private static readonly int[] ExtraLengths = [{", ".join(str(1 + len(vs)) for _, vs in extra)}];
}}
"""
(ROOT / "src" / "TeamLeave" / "CaseFold.g.cs").write_text(text.replace("\n", "\r\n"), encoding="utf-8", newline="")
print(f"{len(lower)} lower-case pairs, {len(self_lower_cased)} cased lower-case, {len(extra)} extra cases")
